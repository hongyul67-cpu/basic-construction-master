function sty(k) { return ST[k === 'pt' ? 'act' : k] || ST.aux; }
function attr(o) {
  var s = sty(o.st);
  return 'fill="none" stroke="' + s.s + '" stroke-width="' + s.w + '"' +
         (s.d ? ' stroke-dasharray="' + s.d + '"' : '') + ' stroke-linecap="round"';
}
function pol(c, r, a) { return [c[0] + r * Math.cos(a), c[1] + r * Math.sin(a)]; }

/* 캔버스 arc(a0→a1, 시계방향) 를 SVG 호로 옮긴다 */
function arcPath(o) {
  var d = o.a1 - o.a0;
  while (d < 0) d += Math.PI * 2;
  if (d > Math.PI * 2 - 1e-6) d = Math.PI * 2 - 1e-6;
  var p0 = pol(o.c, o.r, o.a0), p1 = pol(o.c, o.r, o.a0 + d);
  return 'M' + p0[0].toFixed(2) + ' ' + p0[1].toFixed(2) +
         ' A' + o.r.toFixed(2) + ' ' + o.r.toFixed(2) + ' 0 ' +
         (d > Math.PI ? 1 : 0) + ' 1 ' + p1[0].toFixed(2) + ' ' + p1[1].toFixed(2);
}

function prim(o) {
  if (o.k === 'L') return '<line x1="' + o.a[0] + '" y1="' + o.a[1] + '" x2="' + o.b[0] +
                          '" y2="' + o.b[1] + '" ' + attr(o) + '/>';
  if (o.k === 'A') return '<path d="' + arcPath(o) + '" ' + attr(o) + '/>';
  if (o.k === 'C') return '<circle cx="' + o.c[0] + '" cy="' + o.c[1] + '" r="' + o.r + '" ' + attr(o) + '/>';
  if (o.k === 'E') return '<ellipse cx="' + o.c[0] + '" cy="' + o.c[1] + '" rx="' + o.a +
                          '" ry="' + o.b + '" ' + attr(o) + '/>';
  if (o.k === 'P') {
    var col = o.st === 'given' ? '#cfdcee' : (o.st === 'res' ? '#4ade80' : '#f0a35a');
    return '<circle cx="' + o.p[0] + '" cy="' + o.p[1] + '" r="' + (o.lab ? 4.2 : 3) +
           '" fill="' + col + '"/>' +
           (o.lab ? '<text x="' + o.p[0] + '" y="' + (o.p[1] - 9) + '" text-anchor="middle" ' +
                    'fill="' + col + '" font-size="13" font-weight="800">' + o.lab + '</text>' : '');
  }
  return '';
}

/* 'bisect@2' → 배우기의 0~2 단계를 겹쳐 그린 SVG */
function draw(spec) {
  var C = window.CONS || {};
  var p = String(spec).split('@'), key = p[0], upto = p.length > 1 ? +p[1] : 99;
  var K = C[key];
  if (!K) return '';
  var out = '';
  for (var i = 0; i <= upto && i < K.steps.length; i++)
    (K.steps[i].d || []).forEach(function (o) { out += prim(o); });
  return '<svg viewBox="-8 -8 ' + (VW + 16) + ' ' + (VH + 16) + '" style="max-height:34vh">' +
         out + '</svg>';
}

